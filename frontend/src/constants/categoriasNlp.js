const normalizarSlug = (valor = '') => {
  return String(valor)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/ç/g, 'c')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+/, '')
    .replace(/-+$/, '');
};

export const criarSlugCategoria = (nome = '') => {
  if (ALIASES_CATEGORIAS_NLP[nome]) {
    return ALIASES_CATEGORIAS_NLP[nome];
  }

  const categoriaEncontrada = Object.entries(CATEGORIAS_NLP).find(
    ([slug, categoria]) =>
      slug === nome ||
      categoria.nome === nome ||
      categoria.titulo === nome ||
      normalizarSlug(categoria.nome) === normalizarSlug(nome) ||
      normalizarSlug(categoria.titulo) === normalizarSlug(nome)
  );

  if (categoriaEncontrada) {
    return categoriaEncontrada[0];
  }

  return normalizarSlug(nome);
};

export const obterCategoriaPorSlug = (slug = '') => {
  if (CATEGORIAS_NLP[slug]) {
    return CATEGORIAS_NLP[slug];
  }

  const slugNormalizado = normalizarSlug(slug);

  if (CATEGORIAS_NLP[slugNormalizado]) {
    return CATEGORIAS_NLP[slugNormalizado];
  }

  return null;
};